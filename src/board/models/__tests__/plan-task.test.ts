import { describe, it, expect } from 'vitest';
import { linesOutsideCodeBlocks } from '../plan-task.js';

function outside(...lines: string[]): string[] {
  return linesOutsideCodeBlocks(lines.join('\n'));
}

describe('linesOutsideCodeBlocks', () => {
  it('コードブロックが無ければ、すべての行を返す', () => {
    expect(outside('# 計画', '', '- [ ] 1 つ目', '- [x] 2 つ目')).toEqual([
      '# 計画',
      '',
      '- [ ] 1 つ目',
      '- [x] 2 つ目',
    ]);
  });

  it('``` で囲んだ行を、フェンスの行ごと外す', () => {
    expect(outside('- [x] 前', '```', '- [ ] 例', '```', '- [ ] 後')).toEqual([
      '- [x] 前',
      '- [ ] 後',
    ]);
  });

  it('~~~ で囲んだ行も外す', () => {
    expect(outside('- [x] 前', '~~~', '- [ ] 例', '~~~', '- [ ] 後')).toEqual([
      '- [x] 前',
      '- [ ] 後',
    ]);
  });

  it('言語名付きのフェンスも外す', () => {
    expect(outside('```markdown', '## AI レビュー', '- [ ] 例', '```', '- [ ] 後')).toEqual([
      '- [ ] 後',
    ]);
  });

  it('4 文字のフェンスを 3 文字では閉じない', () => {
    expect(outside('````', '- [ ] 例 1', '```', '- [ ] 例 2', '````', '- [ ] 後')).toEqual([
      '- [ ] 後',
    ]);
  });

  it('閉じるフェンスは開いたものより長くてよい', () => {
    expect(outside('```', '- [ ] 例', '`````', '- [ ] 後')).toEqual(['- [ ] 後']);
  });

  it('``` で開いた範囲を ~~~ では閉じない', () => {
    expect(outside('```', '- [ ] 例 1', '~~~', '- [ ] 例 2', '```', '- [ ] 後')).toEqual([
      '- [ ] 後',
    ]);
  });

  it('言語名などが後ろにある行は閉じるフェンスではない', () => {
    expect(outside('```', '- [ ] 例 1', '```js', '- [ ] 例 2', '```', '- [ ] 後')).toEqual([
      '- [ ] 後',
    ]);
  });

  it('箇条書きの中に字下げして書いたフェンスも外す', () => {
    expect(
      outside('- [ ] 1 つ目', '  - 例:', '    ```', '    - [ ] 例', '    ```', '- [ ] 2 つ目')
    ).toEqual(['- [ ] 1 つ目', '  - 例:', '- [ ] 2 つ目']);
  });

  it('閉じていないフェンスは無かったものとし、後ろの行を残す', () => {
    expect(outside('- [x] 前', '```', '- [ ] 後 1', '- [ ] 後 2')).toEqual([
      '- [x] 前',
      '```',
      '- [ ] 後 1',
      '- [ ] 後 2',
    ]);
  });

  it('閉じていないフェンスの後ろにある、閉じたコードブロックは外す', () => {
    expect(outside('````', '- [ ] 後', '```', '- [ ] 例', '```')).toEqual(['````', '- [ ] 後']);
  });

  it('後ろにバッククォートを含むバッククォートの並びはフェンスではない（インラインコード）', () => {
    expect(outside('```foo` を使う', '- [ ] 後', '```')).toEqual([
      '```foo` を使う',
      '- [ ] 後',
      '```',
    ]);
  });

  it('~~~ の後ろのバッククォートは info として許す', () => {
    expect(outside('~~~ `info`', '- [ ] 例', '~~~', '- [ ] 後')).toEqual(['- [ ] 後']);
  });

  it('字下げしたサブタスクは残す（4 つの空白の字下げをコードブロックとみなさない）', () => {
    expect(outside('- [ ] 1', '    - [ ] 1.1', '        - [x] 1.1.1')).toEqual([
      '- [ ] 1',
      '    - [ ] 1.1',
      '        - [x] 1.1.1',
    ]);
  });

  it('CRLF の改行でも見分ける', () => {
    expect(linesOutsideCodeBlocks('- [x] 前\r\n```\r\n- [ ] 例\r\n```\r\n- [ ] 後')).toEqual([
      '- [x] 前',
      '- [ ] 後',
    ]);
  });
});
